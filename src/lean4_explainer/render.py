def _notice(ctx: "Context") -> str:
    if any(ext.runs_lean for ext, _ in ctx.extensions):
        return "Generated by a source-level scanner, plus a Lean run where it succeeded: see the Trust page. Trust is UNKNOWN wherever Lean did not run. " + _NOTICE_TAIL
    return "Generated by a source-level scanner. Lean was not run, so axiom and trust checks are UNKNOWN. " + _NOTICE_TAIL


@dataclass
class _Folder:
    folders: set[str] = field(default_factory=set)
    files: list[FileSummary] = field(default_factory=list)
    file_count: int = 0
    declarations: int = 0
    sorry: int = 0
    axioms: int = 0


@dataclass(frozen=True)
class Context:
    title: str
    source_url: str | None
    source_ref: str
    locations: Mapping[str, tuple[str, int]]
    cross_links: bool
    search: bool
    status: str = ""
    objects: Objects | None = None
    home: str | None = None
    site_url: str | None = None
    description: str = "Explore Lean declarations, source, explanations, and dependencies."
    project_url: str | None = None
    report_url: str | None = None
    extensions: tuple[tuple[Extension, object], ...] = ()  # active extensions with their analysis of the tree
    options: tuple[tuple[str, object], ...] = ()
    source_links: str = "declaration"
    imports: str = "all"  # what file pages show of the import graph: "all", "import-only" or "none"


def default_context() -> Context:
    return Context(
        title="Lean proofsite",
        source_url=None,
        source_ref="main",
        locations={},
        cross_links=True,
        search=True,
    )


def file_page(lean_file: LeanFile, ctx: Context | None = None, text: str = "") -> str:
    if ctx is None:
        ctx = default_context()
    dirs = lean_file.path.split("/")[:-1]
    name = lean_file.path.split("/")[-1]
    declarations = lean_file.declarations
    sorry = sum(decl.has_sorry for decl in declarations)
    axioms = sum(decl.kind == "axiom" for decl in declarations)
    body = [
        _crumbs(dirs, name),
        _path_title(dirs, name),
    ]
    for ext, analysis in ctx.extensions:
        preamble = ext.file_preamble(lean_file, ctx, analysis)
        if preamble:
            body.append(preamble)
    body.append(f'<p class="muted">{_stats(len(declarations), sorry, axioms)}</p>')
    if ctx.source_url and ctx.source_links == "file":
        href = escape(source_href(lean_file.path, 1, ctx), quote=True)
        body.append(f'<p><a class="src" href="{href}">source</a></p>')
    if lean_file.module_doc:
        body.append(f'<div class="doc">{doc_html(lean_file.module_doc)}</div>')
    shown = ctx.imports == "all" or (ctx.imports == "import-only" and lean_file.import_only)
    if shown:
        body.extend(_import_blocks(lean_file, dirs, ctx))
    if declarations:
        body.append(filter_box("Filter declarations"))
        body.append('<ol class="decls" data-filter-rows>')
        body.extend(_decl_item(decl, lean_file.path, dirs, ctx) for decl in declarations)
        body.append("</ol>")
    elif not (shown and lean_file.import_only):
        body.append('<p class="muted">No declarations listed.</p>')
    for ext, analysis in ctx.extensions:
        block = ext.file_blocks(lean_file, text, ctx, analysis)
        if block:
            body.append(block)
    # A large corpus can have more than 100,000 file pages. Keep their essential SEO and
    # accessibility metadata, but reserve repeated social-card/footer markup for navigation
    # and feature pages so the static artifact remains deployable.
    promoted = any(ext.promote_file_page(lean_file) for ext, _ in ctx.extensions)
    return page(
        lean_file.path,
        len(dirs),
        body,
        ctx,
        canonical_path=lean_file.path + ".html",
        compact=not promoted,
    )


def _import_blocks(lean_file: LeanFile, dirs: list[str], ctx: Context) -> list[str]:
    """What the file imports (linked: a project file to its page, a library module to its documentation) and the
    project files that import it. A file that only imports gets the list open, with a sentence saying so."""
    modules = ctx.objects.modules if ctx.objects is not None else None
    blocks = []
    if lean_file.imports:
        items = []
        for name in lean_file.imports:
            target = modules.file_of(name) if modules is not None else None
            url = href(dirs, target) if target and target != lean_file.path else docs_url(name)
            label = f'<a href="{escape(url, quote=True)}">{escape(name)}</a>' if url else f"<code>{escape(name)}</code>"
            items.append(f"<li>{label}</li>")
        count = len(lean_file.imports)
        if lean_file.import_only:
            gathered = "the import below" if count == 1 else f"the {count} imports below"
            blocks.append(
                f'<p>This file declares nothing itself. It gathers {gathered}, so a file that imports it gets all of them.</p>'
            )
            blocks.append(f'<section class="imports"><h2>Imports</h2><ul class="list">{"".join(items)}</ul></section>')
        else:
            blocks.append(f'<details class="imports"><summary>Imports ({count})</summary><ul class="list">{"".join(items)}</ul></details>')
    users = modules.imported_by.get(lean_file.path, ()) if modules is not None else ()
    if users:
        items = "".join(f'<li><a href="{escape(href(dirs, rel), quote=True)}">{escape(rel)}</a></li>' for rel in users)
        noun = "file" if len(users) == 1 else "files"
        blocks.append(f'<details class="imported-by"><summary>Imported by {len(users)} {noun}</summary><ul class="list">{items}</ul></details>')
    return blocks


def folder_pages(summaries: list[FileSummary], ctx: Context) -> Iterator[tuple[tuple[str, ...], str]]:
    folders: dict[tuple[str, ...], _Folder] = {(): _Folder()}
    for summary in summaries:
        dirs = tuple(summary.path.split("/")[:-1])
        for depth in range(len(dirs) + 1):
            folder = folders.setdefault(dirs[:depth], _Folder())
            folder.file_count += 1
            folder.declarations += summary.declarations
            folder.sorry += summary.sorry
            folder.axioms += summary.axioms
            if depth < len(dirs):
                folder.folders.add(dirs[depth])
        folders[dirs].files.append(summary)
    for dirs, folder in folders.items():
        yield dirs, _folder_page(dirs, folder, folders, ctx)


def _folder_page(
    dirs: tuple[str, ...], folder: _Folder, folders: dict[tuple[str, ...], _Folder], ctx: Context
) -> str:
    body = [_crumbs(dirs, "")]
    if dirs:
        page_title = "/".join(dirs) + "/"
        body.append(f"<h1><code>{escape(page_title)}</code></h1>")
    else:
        page_title = ctx.title
        body.append(f"<h1>{escape(ctx.title)}</h1>")
        body.append(f'<p class="muted">{escape(_notice(ctx))}</p>')
        body.append(_summary_list(folder))
        if ctx.status:
            body.append(f'<p class="muted">{escape(ctx.status)}</p>')
    body.append(
        f'<p class="muted">{_stats(folder.declarations, folder.sorry, folder.axioms)}; '
        f"{folder.file_count} files</p>"
    )
    body.append(filter_box("Filter folders and files"))
    if folder.folders:
        body.append('<section data-filter-section><h2>Folders</h2>')
        body.append('<ul class="list" data-filter-rows>')
        for name in sorted(folder.folders):
            child = folders[(*dirs, name)]
            body.append(
                f'<li><a href="{quote(name)}/index.html">{escape(name)}/</a> '
                f'<span class="muted">{child.file_count} files, {child.declarations} declarations</span></li>'
            )
        body.append("</ul></section>")
    if folder.files:
        body.append('<section data-filter-section><h2>Files</h2>')
        body.append('<ul class="list" data-filter-rows>')
        for summary in sorted(folder.files, key=lambda s: s.path):
            name = summary.path.split("/")[-1]
            body.append(
                f'<li><a href="{quote(name)}.html">{escape(name)}</a> '
                f'<span class="muted">{_file_note(summary)}</span></li>'
            )
        body.append("</ul></section>")
    canonical = "/".join((*dirs, "index.html")) if dirs else "index.html"
    return page(page_title, len(dirs), body, ctx, canonical_path=canonical)


def _file_note(summary: FileSummary) -> str:
    if summary.import_only:
        return f"{summary.imports} import{'' if summary.imports == 1 else 's'}, no declarations"
    return f"{summary.declarations} declarations"


def _summary_list(folder: _Folder) -> str:
    rows = [
        ("Lean files", folder.file_count),
        ("Declarations", folder.declarations),
        ("Contain sorry", folder.sorry),
        ("Axioms", folder.axioms),
    ]
    items = "".join(f"<dt>{escape(label)}</dt><dd>{value}</dd>" for label, value in rows)
    return f'<dl class="summary">{items}</dl>'



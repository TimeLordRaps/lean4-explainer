def _stats(declarations: int, sorry: int, axioms: int) -> str:
    return f"{declarations} declarations, {sorry} contain sorry, {axioms} axioms"


def up_path(levels: int) -> str:
    return "../" * levels


def _crumbs(dirs: list[str] | tuple[str, ...], tail: str) -> str:
    items = [f'<a href="{up_path(len(dirs))}index.html">Corpus home</a>']
    for depth, name in enumerate(dirs, start=1):
        items.append(f'<a href="{up_path(len(dirs) - depth)}index.html">{escape(name)}</a>')
    if tail:
        items.append(f"<span>{escape(tail)}</span>")
    return '<nav class="crumbs" aria-label="Breadcrumb">' + " / ".join(items) + "</nav>"


def _path_title(dirs: list[str] | tuple[str, ...], tail: str) -> str:
    items = []
    for depth, name in enumerate(dirs, start=1):
        target = up_path(len(dirs) - depth) + "index.html"
        items.append(f'<a href="{target}">{escape(name)}</a>')
    items.append(f"<span>{escape(tail)}</span>")
    return '<h1 class="path-title"><code>' + "/".join(items) + "</code></h1>"


def page(
    title: str,
    depth: int,
    body: list[str],
    ctx: Context,
    *,
    canonical_path: str | None = None,
    description: str | None = None,
    compact: bool = False,
) -> str:
    up = up_path(depth)
    links = [("All corpora", f"{up}{ctx.home}")] if ctx.home else []
    links.append(("Index", f"{up}index.html"))
    links.append(("Glossary", f"{up}glossary.html"))  # every build writes it
    for ext, _ in ctx.extensions:
        links.extend(ext.nav_links(up, dict(ctx.options)))
    if ctx.search:
        links.append(("Search", f"{up}search.html"))
    nav = '<nav class="top">' + " | ".join(f'<a href="{href}">{label}</a>' for label, href in links) + "</nav>"
    header = ['<header class="site-head">', nav]
    content = body
    if body and body[0].startswith('<nav class="crumbs"'):
        header.append(body[0])
        content = body[1:]
    header.append("</header>")
    description = description or ctx.description
    full_title = ctx.title if title == ctx.title else f"{title} — {ctx.title}"
    canonical = (
        urljoin(ctx.site_url.rstrip("/") + "/", quote(canonical_path, safe="/"))
        if ctx.site_url and canonical_path
        else ""
    )
    meta = [f'<meta name="description" content="{escape(description, quote=True)}">']
    if not compact:
        meta.extend(
            [
                f'<meta property="og:title" content="{escape(full_title, quote=True)}">',
                f'<meta property="og:description" content="{escape(description, quote=True)}">',
                '<meta property="og:type" content="website">',
                '<meta name="twitter:card" content="summary">',
            ]
        )
    if canonical:
        meta.append(f'<link rel="canonical" href="{escape(canonical, quote=True)}">')
        if not compact:
            meta.append(f'<meta property="og:url" content="{escape(canonical, quote=True)}">')
    footer_links = []
    if ctx.project_url:
        footer_links.append(f'<a href="{escape(ctx.project_url, quote=True)}">Project source</a>')
    if ctx.report_url:
        footer_links.append(f'<a href="{escape(ctx.report_url, quote=True)}">Report a site issue</a>')
    footer = f'<footer class="site-footer">{" · ".join(footer_links)}</footer>' if footer_links and not compact else ""
    return "\n".join(
        [
            "<!doctype html>",
            '<html lang="en">',
            "<head>",
            '<meta charset="utf-8">',
            '<meta name="viewport" content="width=device-width, initial-scale=1">',
            f"<title>{escape(full_title)}</title>",
            *meta,
            f'<link rel="stylesheet" href="{up}{ASSET_DIR}/site.css">',
            f'<link rel="icon" href="{up}{ASSET_DIR}/favicon.svg" type="image/svg+xml">',
            "</head>",
            f'<body data-root="{up}">',
            '<a class="skip-link" href="#content">Skip to content</a>',
            '<main id="content" tabindex="-1">',
            *header,
            *content,
            "</main>",
            footer,
            f'<script src="{up}{ASSET_DIR}/site.js"></script>',
            *(
                f'<script src="{escape(up + path, quote=True)}" defer></script>'
                for ext, _ in ctx.extensions
                for path in ext.scripts(dict(ctx.options))
            ),
            "</body>",
            "</html>",
            "",
        ]
    )

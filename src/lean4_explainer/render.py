def _decl_item(decl: Declaration, rel: str, dirs: list[str], ctx: Context) -> str:
    head = f'<b>{escape(decl.kind)}</b> <code>{escape(decl.name)}</code>'
    for ext, _ in ctx.extensions:
        if ext.name in decl.ext:
            head += ext.declaration_title(decl, decl.ext[ext.name])
    if decl.has_sorry:
        head += ' <span class="flag sorry">sorry</span>'
    head += f' <small>line {decl.line}</small>'
    if ctx.source_url and ctx.source_links == "declaration":
        href = escape(source_href(rel, decl.line, ctx), quote=True)
        head += f' <a class="src" href="{href}">source</a>'
    parts = [f'<li id=L{decl.line}>{head}']
    if decl.doc:  # a doc comment is Markdown; a plain comment above a declaration is shown as written
        parts.append(f'<div class="doc">{doc_html(decl.doc)}</div>')
    elif decl.comment:
        parts.append(f'<div class="doc plain">{escape(decl.comment)}</div>')
    before: list[str] = []
    after: list[str] = []
    for ext, analysis in ctx.extensions:
        if ext.name in decl.ext or ext.every_declaration:
            top, bottom = ext.declaration_blocks(decl, decl.ext.get(ext.name), rel, dirs, ctx, analysis)
            before.append(top)
            after.append(bottom)
    parts.extend(block for block in before if block)
    copies = _copies(decl, rel, dirs, ctx)
    if copies:
        parts.append(copies)
    parts.extend(block for block in after if block)
    if decl.statement:
        parts.append(f"<pre>{escape(decl.statement)}</pre>")
        if ctx.cross_links:
            mentions = _mentions(decl, dirs, ctx)
            if mentions:
                parts.append(mentions)
    parts.append("</li>")
    return "\n".join(parts)


def _objects(ctx: Context) -> Objects:
    return ctx.objects or plain_objects(ctx.locations)


def _copies(decl: Declaration, rel: str, dirs: list[str], ctx: Context) -> str:
    objects = _objects(ctx)
    others = [copy for copy in objects.copies.get(decl.name, ()) if copy.rel != rel]
    if not others:
        return ""
    items = []
    for copy in others:
        if copy.code == decl.code_digest:
            how = "identical"
        elif copy.header == decl.header_digest:
            how = "same statement, different proof or body"
        else:
            how = "different statement"
        link = escape(href(dirs, copy.rel, f"#L{copy.line}"), quote=True)
        items.append(f'<a href="{link}">{escape(copy.rel)}:{copy.line}</a> ({how})')
    if decl.name in objects.ambiguous:
        label = "Distinct definitions of this name"
        tail = f" Qualify references as {escape(decl.name)}@path."
    else:
        label = "Also declared"
        tail = ""
    return f'<p class="refs">{label}: ' + ", ".join(items) + "." + tail + "</p>"


def refs(label: str, tokens: Iterable[str], scope: list[str] | None, dirs: list[str], ctx: Context) -> str:
    objects = _objects(ctx)
    items = []
    for token in tokens:
        if scope is None:
            target = resolve_exact(token, objects)
        else:
            target = resolve(token, scope, ctx.locations, objects.ambiguous)
        if target is None:
            items.append(f'<span class="warn">{escape(token)}</span>')
            continue
        rel, line = ctx.locations[target]
        link = escape(href(dirs, rel, f"#L{line}"), quote=True)
        items.append(f'<a href="{link}">{escape(target)}</a>')
    return f'<p class="refs">{escape(label)}: ' + ", ".join(items) + "</p>"


def _mentions(decl: Declaration, dirs: list[str], ctx: Context) -> str:
    scope = decl.name.split(".")[:-1]
    found: list[str] = []
    for token in _IDENT_RE.findall(decl.statement):
        target = resolve(token, scope, ctx.locations, _objects(ctx).ambiguous)
        if target is not None and target != decl.name and target not in found:
            found.append(target)
            if len(found) == _MENTION_LIMIT:
                break
    return refs("Mentions", found, [], dirs, ctx) if found else ""


def source_href(rel: str, line: int, ctx: Context) -> str:
    url = ctx.source_url or ""
    return url.replace("{path}", quote(rel)).replace("{line}", str(line)).replace("{ref}", ctx.source_ref)


def href(from_dirs: list[str], to_rel: str, anchor: str = "") -> str:
    parts = to_rel.split("/")
    to_dirs = parts[:-1]
    common = 0
    while common < min(len(from_dirs), len(to_dirs)) and from_dirs[common] == to_dirs[common]:
        common += 1
    segments = [quote(part) for part in parts[common:]]
    segments[-1] += ".html"
    return "../" * (len(from_dirs) - common) + "/".join(segments) + anchor



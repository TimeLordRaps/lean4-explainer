@dataclass
class _Folder:
    folders: set[str] = field(default_factory=set)
    files: list[FileSummary] = field(default_factory=list)
    file_count: int = 0
    declarations: int = 0
    sorry: int = 0
    axioms: int = 0


@dataclass(frozen=True)
class Context:
    title: str
    source_url: str | None
    source_ref: str
    locations: Mapping[str, tuple[str, int]]
    cross_links: bool
    search: bool
    status: str = ""
    objects: Objects | None = None
    home: str | None = None
    extensions: tuple[tuple[Extension, object], ...] = ()  # active extensions with their analysis of the tree
    options: tuple[tuple[str, object], ...] = ()
    source_links: str = "declaration"
    imports: str = "all"  # what file pages show of the import graph: "all", "import-only" or "none"


def default_context() -> Context:
    return Context(
        title="Lean proofsite",
        source_url=None,
        source_ref="main",
        locations={},
        cross_links=True,
        search=True,
    )


def file_page(lean_file: LeanFile, ctx: Context | None = None, text: str = "") -> str:
    if ctx is None:
        ctx = default_context()
    dirs = lean_file.path.split("/")[:-1]
    name = lean_file.path.split("/")[-1]
    declarations = lean_file.declarations
    sorry = sum(decl.has_sorry for decl in declarations)
    axioms = sum(decl.kind == "axiom" for decl in declarations)
    body = [
        _crumbs(dirs, name),
        f"<h1><code>{escape(lean_file.path)}</code></h1>",
        f'<p class="muted">{_stats(len(declarations), sorry, axioms)}</p>',
    ]
    if ctx.source_url and ctx.source_links == "file":
        href = escape(source_href(lean_file.path, 1, ctx), quote=True)
        body.append(f'<p><a class="src" href="{href}">source</a></p>')
    if lean_file.module_doc:
        body.append(f'<div class="doc">{doc_html(lean_file.module_doc)}</div>')
    shown = ctx.imports == "all" or (ctx.imports == "import-only" and lean_file.import_only)
    if shown:
        body.extend(_import_blocks(lean_file, dirs, ctx))
    if declarations:
        body.append(_FILTER_HTML)
        body.append('<ol class="decls">')
        body.extend(_decl_item(decl, lean_file.path, dirs, ctx) for decl in declarations)
        body.append("</ol>")
    elif not (shown and lean_file.import_only):
        body.append('<p class="muted">No declarations listed.</p>')
    for ext, analysis in ctx.extensions:
        block = ext.file_blocks(lean_file, text, ctx, analysis)
        if block:
            body.append(block)
    return page(lean_file.path, len(dirs), body, ctx)


def _import_blocks(lean_file: LeanFile, dirs: list[str], ctx: Context) -> list[str]:
    """What the file imports (linked: a project file to its page, a library module to its documentation) and the
    project files that import it. A file that only imports gets the list open, with a sentence saying so."""
    modules = ctx.objects.modules if ctx.objects is not None else None
    blocks = []
    if lean_file.imports:
        items = []
        for name in lean_file.imports:
            target = modules.file_of(name) if modules is not None else None
            url = href(dirs, target) if target and target != lean_file.path else docs_url(name)
            label = f'<a href="{escape(url, quote=True)}">{escape(name)}</a>' if url else f"<code>{escape(name)}</code>"
            items.append(f"<li>{label}</li>")
        count = len(lean_file.imports)
        if lean_file.import_only:
            gathered = "the import below" if count == 1 else f"the {count} imports below"
            blocks.append(
                f'<p>This file declares nothing itself. It gathers {gathered}, so a file that imports it gets all of them.</p>'
            )
            blocks.append(f'<section class="imports"><h2>Imports</h2><ul class="list">{"".join(items)}</ul></section>')
        else:
            blocks.append(f'<details class="imports"><summary>Imports ({count})</summary><ul class="list">{"".join(items)}</ul></details>')
    users = modules.imported_by.get(lean_file.path, ()) if modules is not None else ()
    if users:
        items = "".join(f'<li><a href="{escape(href(dirs, rel), quote=True)}">{escape(rel)}</a></li>' for rel in users)
        noun = "file" if len(users) == 1 else "files"
        blocks.append(f'<details class="imported-by"><summary>Imported by {len(users)} {noun}</summary><ul class="list">{items}</ul></details>')
    return blocks


def folder_pages(summaries: list[FileSummary], ctx: Context) -> Iterator[tuple[tuple[str, ...], str]]:
    folders: dict[tuple[str, ...], _Folder] = {(): _Folder()}
    for summary in summaries:
        dirs = tuple(summary.path.split("/")[:-1])
        for depth in range(len(dirs) + 1):
            folder = folders.setdefault(dirs[:depth], _Folder())
            folder.file_count += 1
            folder.declarations += summary.declarations
            folder.sorry += summary.sorry
            folder.axioms += summary.axioms
            if depth < len(dirs):
                folder.folders.add(dirs[depth])
        folders[dirs].files.append(summary)
    for dirs, folder in folders.items():
        yield dirs, _folder_page(dirs, folder, folders, ctx)


def _folder_page(
    dirs: tuple[str, ...], folder: _Folder, folders: dict[tuple[str, ...], _Folder], ctx: Context
) -> str:
    body = [_crumbs(dirs, "")]
    if dirs:
        page_title = "/".join(dirs) + "/"
        body.append(f"<h1><code>{escape(page_title)}</code></h1>")
    else:
        page_title = ctx.title
        body.append(f"<h1>{escape(ctx.title)}</h1>")
        body.append(f'<p class="muted">{escape(_notice(ctx))}</p>')
        body.append(_summary_list(folder))
        if ctx.status:
            body.append(f'<p class="muted">{escape(ctx.status)}</p>')
    body.append(
        f'<p class="muted">{_stats(folder.declarations, folder.sorry, folder.axioms)}; '
        f"{folder.file_count} files</p>"
    )
    body.append(_FILTER_HTML)
    if folder.folders:
        body.append("<h2>Folders</h2>")
        body.append('<ul class="list">')
        for name in sorted(folder.folders):
            child = folders[(*dirs, name)]
            body.append(
                f'<li data-filterable><a href="{quote(name)}/index.html">{escape(name)}/</a> '
                f'<span class="muted">{child.file_count} files, {child.declarations} declarations</span></li>'
            )
        body.append("</ul>")
    if folder.files:
        body.append("<h2>Files</h2>")
        body.append('<ul class="list">')
        for summary in sorted(folder.files, key=lambda s: s.path):
            name = summary.path.split("/")[-1]
            body.append(
                f'<li data-filterable><a href="{quote(name)}.html">{escape(name)}</a> '
                f'<span class="muted">{_file_note(summary)}</span></li>'
            )
        body.append("</ul>")
    return page(page_title, len(dirs), body, ctx)


def _file_note(summary: FileSummary) -> str:
    if summary.import_only:
        return f"{summary.imports} import{'' if summary.imports == 1 else 's'}, no declarations"
    return f"{summary.declarations} declarations"


def _summary_list(folder: _Folder) -> str:
    rows = [
        ("Lean files", folder.file_count),
        ("Declarations", folder.declarations),
        ("Contain sorry", folder.sorry),
        ("Axioms", folder.axioms),
    ]
    items = "".join(f"<dt>{escape(label)}</dt><dd>{value}</dd>" for label, value in rows)
    return f'<dl class="summary">{items}</dl>'


_IDENT_RE = re.compile(r"[^\W\d][\w'.!?]*")
_MENTION_LIMIT = 25


def _decl_item(decl: Declaration, rel: str, dirs: list[str], ctx: Context) -> str:
    head = f'<span class="kind">{escape(decl.kind)}</span> <code>{escape(decl.name)}</code>'
    for ext, _ in ctx.extensions:
        if ext.name in decl.ext:
            head += ext.declaration_title(decl, decl.ext[ext.name])
    if decl.has_sorry:
        head += ' <span class="flag sorry">sorry</span>'
    head += f' <span class="ln">line {decl.line}</span>'
    if ctx.source_url and ctx.source_links == "declaration":
        href = escape(source_href(rel, decl.line, ctx), quote=True)
        head += f' <a class="src" href="{href}">source</a>'
    parts = [f'<li id="L{decl.line}" data-filterable>{head}']
    if decl.doc:  # a doc comment is Markdown; a plain comment above a declaration is shown as written
        parts.append(f'<div class="doc">{doc_html(decl.doc)}</div>')
    elif decl.comment:
        parts.append(f'<div class="doc plain">{escape(decl.comment)}</div>')
    before: list[str] = []
    after: list[str] = []
    for ext, analysis in ctx.extensions:
        if ext.name in decl.ext:
            top, bottom = ext.declaration_blocks(decl, decl.ext[ext.name], rel, dirs, ctx, analysis)
            before.append(top)
            after.append(bottom)
    parts.extend(block for block in before if block)
    copies = _copies(decl, rel, dirs, ctx)
    if copies:
        parts.append(copies)
    parts.extend(block for block in after if block)
    if decl.statement:
        parts.append(f"<pre>{escape(decl.statement)}</pre>")
        if ctx.cross_links:
            mentions = _mentions(decl, dirs, ctx)
            if mentions:
                parts.append(mentions)
    parts.append("</li>")
    return "\n".join(parts)


def _objects(ctx: Context) -> Objects:
    return ctx.objects or plain_objects(ctx.locations)


def _copies(decl: Declaration, rel: str, dirs: list[str], ctx: Context) -> str:
    objects = _objects(ctx)
    others = [copy for copy in objects.copies.get(decl.name, ()) if copy.rel != rel]
    if not others:
        return ""
    items = []
    for copy in others:
        if copy.code == decl.code_digest:
            how = "identical"
        elif copy.header == decl.header_digest:
            how = "same statement, different proof or body"
        else:
            how = "different statement"
        link = escape(href(dirs, copy.rel, f"#L{copy.line}"), quote=True)
        items.append(f'<a href="{link}">{escape(copy.rel)}:{copy.line}</a> ({how})')
    if decl.name in objects.ambiguous:
        label = "Distinct definitions of this name"
        tail = f" Qualify references as {escape(decl.name)}@path."
    else:
        label = "Also declared"
        tail = ""
    return f'<p class="refs">{label}: ' + ", ".join(items) + "." + tail + "</p>"


def refs(label: str, tokens: Iterable[str], scope: list[str] | None, dirs: list[str], ctx: Context) -> str:
    objects = _objects(ctx)
    items = []
    for token in tokens:
        if scope is None:
            target = resolve_exact(token, objects)
        else:
            target = resolve(token, scope, ctx.locations, objects.ambiguous)
        if target is None:
            items.append(f'<span class="warn">{escape(token)}</span>')
            continue
        rel, line = ctx.locations[target]
        link = escape(href(dirs, rel, f"#L{line}"), quote=True)
        items.append(f'<a href="{link}">{escape(target)}</a>')
    return f'<p class="refs">{escape(label)}: ' + ", ".join(items) + "</p>"


def _mentions(decl: Declaration, dirs: list[str], ctx: Context) -> str:
    scope = decl.name.split(".")[:-1]
    found: list[str] = []
    for token in _IDENT_RE.findall(decl.statement):
        target = resolve(token, scope, ctx.locations, _objects(ctx).ambiguous)
        if target is not None and target != decl.name and target not in found:
            found.append(target)
            if len(found) == _MENTION_LIMIT:
                break
    return refs("Mentions", found, [], dirs, ctx) if found else ""


def source_href(rel: str, line: int, ctx: Context) -> str:
    url = ctx.source_url or ""
    return url.replace("{path}", quote(rel)).replace("{line}", str(line)).replace("{ref}", ctx.source_ref)


def href(from_dirs: list[str], to_rel: str, anchor: str = "") -> str:
    parts = to_rel.split("/")
    to_dirs = parts[:-1]
    common = 0
    while common < min(len(from_dirs), len(to_dirs)) and from_dirs[common] == to_dirs[common]:
        common += 1
    segments = [quote(part) for part in parts[common:]]
    segments[-1] += ".html"
    return "../" * (len(from_dirs) - common) + "/".join(segments) + anchor


def search_page(ctx: Context) -> str:
    body = [
        "<h1>Search</h1>",
        '<input id="q" type="search" placeholder="Declaration name prefix, two or more characters">',
        '<ol id="results" class="list"></ol>',
        '<p class="muted">Matches qualified names that start with the query.</p>',
        f'<script src="{ASSET_DIR}/search/files.js"></script>',
    ]
    return page("Search", 0, body, ctx)


def _stats(declarations: int, sorry: int, axioms: int) -> str:
    return f"{declarations} declarations, {sorry} contain sorry, {axioms} axioms"


def up_path(levels: int) -> str:
    return "../" * levels


def _crumbs(dirs: list[str] | tuple[str, ...], tail: str) -> str:
    items = [f'<a href="{up_path(len(dirs))}index.html">lean</a>']
    for depth, name in enumerate(dirs, start=1):
        items.append(f'<a href="{up_path(len(dirs) - depth)}index.html">{escape(name)}</a>')
    if tail:
        items.append(f"<span>{escape(tail)}</span>")
    return '<nav class="crumbs">' + " / ".join(items) + "</nav>"


def page(title: str, depth: int, body: list[str], ctx: Context) -> str:
    up = up_path(depth)
    links = [("All corpora", f"{up}{ctx.home}")] if ctx.home else []
    links.append(("Index", f"{up}index.html"))
    links.append(("Glossary", f"{up}glossary.html"))  # every build writes it
    for ext, _ in ctx.extensions:
        links.extend(ext.nav_links(up, dict(ctx.options)))
    if ctx.search:
        links.append(("Search", f"{up}search.html"))
    nav = '<nav class="top">' + " | ".join(f'<a href="{href}">{label}</a>' for label, href in links) + "</nav>"
    return "\n".join(
        [
            "<!doctype html>",
            '<html lang="en">',
            "<head>",
            '<meta charset="utf-8">',
            '<meta name="viewport" content="width=device-width, initial-scale=1">',
            f"<title>{escape(title)}</title>",
            f'<link rel="stylesheet" href="{up}{ASSET_DIR}/site.css">',
            "</head>",
            f'<body data-root="{up}">',
            "<main>",
            nav,
            *body,
            "</main>",
            f'<script src="{up}{ASSET_DIR}/site.js"></script>',
            *(
                f'<script src="{escape(up + path, quote=True)}" defer></script>'
                for ext, _ in ctx.extensions
                for path in ext.scripts(dict(ctx.options))
            ),
            "</body>",
            "</html>",
            "",
        ]
    )
